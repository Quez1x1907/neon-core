// LANG инициализируется в main.js после загрузки сохранения
let LANG = 'en';
function t(key, params){
  let s = (I18N[LANG] && I18N[LANG][key] !== undefined) ? I18N[LANG][key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
  if (params) for (const k in params) s = s.split('{'+k+'}').join(params[k]);
  return s;
}
function applyStaticI18n(root){
  (root||document).querySelectorAll('[data-i]').forEach(el=>{ el.textContent = t(el.getAttribute('data-i')); });
}
